"""Dozen — a multi-agent model orchestrator.

A single entry point (`Orchestrator`) that behaves like one model but, under the
hood, decomposes a task into a dependency graph of subtasks, routes each subtask
to the most suitable model in a swappable agent pool, verifies the results, and
synthesizes them into one coherent answer.

Inspired by learned model orchestration (e.g. Sakana AI's Fugu). This is a
from-scratch, transparent implementation of the *control flow*; the actual
LLM API calls are intentionally left as commented placeholders in
``dozen/llm_client.py`` for you to fill in.
"""

